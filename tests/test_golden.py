STRINGIFY = json.loads(read_text(FIXTURES / 'goldens' / 'stringify.json'))
METADATA = json.loads(read_text(FIXTURES / 'goldens' / 'metadata.json'))


@pytest.mark.parametrize('path', json_fixture_paths(), ids=[p.name for p in json_fixture_paths()])
def test_stringify_is_pinned(path):
    expected = STRINGIFY[path.name]
    assert pf.stringify(load_text(read_text(path))) == expected['newlines']
    assert pf.stringify(load_text(read_text(path)), newlines=False) == expected['no_newlines']


@pytest.mark.parametrize('path', json_fixture_paths(), ids=[p.name for p in json_fixture_paths()])
def test_get_metadata_is_pinned(path):
    assert load_text(read_text(path)).get_metadata() == METADATA[path.name]


def test_goldens_cover_all_fixtures():
    names = {p.name for p in json_fixture_paths()}
    assert set(STRINGIFY) == names
    assert set(METADATA) == names
