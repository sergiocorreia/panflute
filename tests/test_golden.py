# Coverage of the corpus itself
# ---------------------------------------------------------------------------

# Element classes that pandoc can never emit (Null was removed from
# pandoc-types 1.23) or that are only ever built from Python.
NOT_IN_CORPUS = {'Null', 'Doc'}


def test_corpus_covers_every_element_class():
    seen = set()

    def action(elem, doc):
        seen.add(type(elem).__name__)

    for path in json_fixture_paths():
        load_text(read_text(path)).walk(action)

    element_classes = {
        name for name in dir(pf)
        if isinstance(getattr(pf, name), type)
        and issubclass(getattr(pf, name), pf.Element)
        and getattr(pf, name) not in (pf.Element, pf.Block, pf.Inline, pf.MetaValue)
    }
    missing = element_classes - seen - NOT_IN_CORPUS
    assert not missing


def test_corpus_covers_all_enumerations():
    from panflute.elements import (
        CITATION_MODE, LIST_NUMBER_DELIMITERS, LIST_NUMBER_STYLES, MATH_FORMATS,
        QUOTE_TYPES)
    from panflute.table_elements import TABLE_ALIGNMENT
    values = set()

    def action(elem, doc):
        for attr in ('mode', 'style', 'delimiter', 'format', 'quote_type', 'alignment'):
            value = getattr(elem, attr, None)
            if isinstance(value, str):
                values.add(value)
        if isinstance(elem, pf.Table):
            values.update(a for a, _ in elem.colspec)

    for path in json_fixture_paths():
        load_text(read_text(path)).walk(action)

    for group in (CITATION_MODE, LIST_NUMBER_DELIMITERS, LIST_NUMBER_STYLES,
                  MATH_FORMATS, QUOTE_TYPES, TABLE_ALIGNMENT):
        assert group <= values, group - values


