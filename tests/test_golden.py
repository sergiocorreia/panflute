def _walk_order(doc):
    # Same algorithm as fixtures/regenerate.py::walk_order
    def depth(elem):
        d = 0
        while elem.parent is not None:
            elem = elem.parent
            d += 1
        return d

    visited = []
    doc.walk(lambda elem, doc: visited.append(f'{depth(elem)} {elem.tag}'))
    return visited


def test_walk_order_is_pinned():
    doc = load_text(read_text(FIXTURES / 'json' / 'kitchen_sink.json'))
    expected = read_text(FIXTURES / 'goldens' / 'walk-kitchen_sink.txt').splitlines()
    assert _walk_order(doc) == expected


def test_walk_order_small_document():
    """Hand-written expectation: children (in _children order) before parents."""
    doc = pf.Doc(
        pf.Header(pf.Str('H'), level=2),
        pf.Para(pf.Emph(pf.Str('a'), pf.Space), pf.Note(pf.Plain(pf.Str('n')))),
        pf.BulletList(pf.ListItem(pf.Plain(pf.Str('i')))),
        metadata={'k': pf.MetaInlines(pf.Str('m')), 'b': True},
    )
    order = [e.tag for e in _collect(doc)]
    assert order == [
        'Str', 'MetaInlines', 'MetaBool', 'MetaMap',
        'Str', 'Header',
        'Str', 'Space', 'Emph', 'Str', 'Plain', 'Note', 'Para',
        'Str', 'Plain', 'ListItem', 'BulletList',
        'Doc',
    ]


def test_walk_order_compound_elements():
    cite = pf.Cite(pf.Str('text'), citations=[
        pf.Citation('id', prefix=[pf.Str('pre')], suffix=[pf.Str('suf')])])
    assert [e.tag for e in _collect(cite)] == ['Str', 'Str', 'Str', 'Citation', 'Cite']
    assert [e.text for e in _collect(cite) if isinstance(e, pf.Str)] == ['text', 'pre', 'suf']

    dl = pf.DefinitionList(pf.DefinitionItem(
        [pf.Str('term')], [pf.Definition(pf.Plain(pf.Str('def')))]))
    assert [e.tag for e in _collect(dl)] == [
        'Str', 'Str', 'Plain', 'Definition', 'DefinitionItem', 'DefinitionList']

    fig = pf.Figure(pf.Plain(pf.Str('body')),
                    caption=pf.Caption(pf.Plain(pf.Str('cap')), short_caption=[pf.Str('short')]))
    assert [getattr(e, 'text', e.tag) for e in _collect(fig)] == [
        'body', 'Plain', 'cap', 'Plain', 'short', 'Caption', 'Figure']

    lb = pf.LineBlock(pf.LineItem(pf.Str('l1')), pf.LineItem())
    assert [e.tag for e in _collect(lb)] == ['Str', 'LineItem', 'LineItem', 'LineBlock']


def test_walk_order_table():
    def cell(text):
        return pf.TableCell(pf.Plain(pf.Str(text)))

    table = pf.Table(
        pf.TableBody(pf.TableRow(cell('body')), head=[pf.TableRow(cell('ihead'))]),
        head=pf.TableHead(pf.TableRow(cell('head'))),
        foot=pf.TableFoot(pf.TableRow(cell('foot'))),
        caption=pf.Caption(pf.Plain(pf.Str('caption'))),
    )
    texts = [e.text for e in _collect(table) if isinstance(e, pf.Str)]
    # Table: head, bodies, foot, caption. TableBody: rows *before* its intermediate head.
    assert texts == ['head', 'body', 'ihead', 'foot', 'caption']
    row = ['Str', 'Plain', 'TableCell', 'TableRow']
    assert [e.tag for e in _collect(table)] == (
        row + ['TableHead']
        + row + row + ['TableBody']
        + row + ['TableFoot']
        + ['Str', 'Plain', 'Caption']
        + ['Table'])


def _collect(elem):
    visited = []
    elem.walk(lambda e, doc: visited.append(e))
    return visited


