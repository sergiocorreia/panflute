"""
Characterisation ("golden") tests on stored pandoc JSON fixtures.

The fixtures in fixtures/json/ and fixtures/benchmarks/ were produced by
pandoc (see fixtures/regenerate.py), so none of these tests need pandoc.
They pin down that panflute reproduces pandoc's JSON exactly:

- load -> dump gives back the same JSON value (and, up to the order of the
  keys of Citation objects, the very same bytes),
- walking the tree with an action that changes nothing changes nothing,
- the order in which walk() visits the elements of a representative
  document, and the output of stringify() and get_metadata() on every
  fixture, are stable (fixtures/goldens/, generated by panflute itself).
"""

import io
import json

import pytest

import panflute as pf

from .helpers import (
    FIXTURES, benchmark_paths, canonical_pandoc_json, dump_text,
    json_fixture_paths, load_text, read_text)


ALL_FIXTURES = json_fixture_paths() + benchmark_paths()
IDS = [p.name for p in ALL_FIXTURES]
NO_CITATIONS = [p for p in ALL_FIXTURES if '"citationId"' not in read_text(p)]


@pytest.fixture(scope='module', params=ALL_FIXTURES, ids=IDS)
def fixture_text(request):
    return read_text(request.param)


def test_fixture_corpus_is_present():
    assert len(json_fixture_paths()) >= 20
    assert [p.stem for p in benchmark_paths()] == ['awesome-c', 'barcode', 'portugal']


def test_load_dump_same_json_value(fixture_text):
    doc = load_text(fixture_text)
    assert isinstance(doc, pf.Doc)
    assert json.loads(dump_text(doc)) == json.loads(fixture_text)


def test_load_dump_same_bytes_modulo_citation_key_order(fixture_text):
    out = dump_text(load_text(fixture_text))
    assert out == canonical_pandoc_json(fixture_text)


@pytest.mark.parametrize('path', NO_CITATIONS, ids=[p.name for p in NO_CITATIONS])
def test_load_dump_same_bytes_without_citations(path):
    # panflute orders the keys of Citation objects differently from pandoc,
    # but otherwise reproduces its output byte for byte
    fixture_text = read_text(path)
    out = dump_text(load_text(fixture_text))
    # pandoc ends its output with a newline; panflute does not
    assert out == fixture_text.rstrip('\n')


def test_dump_is_idempotent(fixture_text):
    once = dump_text(load_text(fixture_text))
    twice = dump_text(load_text(once))
    assert once == twice


def test_noop_walk_changes_nothing(fixture_text):
    doc = load_text(fixture_text)
    before = dump_text(doc)
    visited = []

    def action(elem, doc):
        visited.append(elem)

    result = doc.walk(action)
    assert result is doc
    assert dump_text(doc) == before
    assert visited[-1] is doc


def test_noop_run_filter_through_streams(fixture_text):
    out = io.StringIO()
    pf.run_filter(lambda elem, doc: None,
                  input_stream=io.StringIO(fixture_text), output_stream=out)
    assert out.getvalue() == canonical_pandoc_json(fixture_text)


def test_returning_same_element_changes_nothing(fixture_text):
    doc = load_text(fixture_text)
    before = dump_text(doc)
    doc = pf.run_filters([lambda e, d: e, lambda e, d: None], doc=doc)
    assert dump_text(doc) == before


def test_loaded_documents_are_equal(fixture_text):
    assert load_text(fixture_text) == load_text(fixture_text)


